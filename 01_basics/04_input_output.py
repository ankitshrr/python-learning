# This program takes input from the user and displays it using the print() function.

# Taking first name as input
name = input("Enter your first name: ")

# Taking last name as input
lastName = input("Enter your last name: ")

# Displaying first name
print("First Name:", name)

# Displaying last name
print("Last Name:", lastName)

# Displaying full name
print("Your full name is:", name, lastName)