# My first Python code

# Example 1: Display text on screen
print("HelloWorld!")  # print() displays output on screen

# Example 2: Print a greeting
print("Hello, World!")
print("Welcome to my Python learning journey!")

# Example 3: Print multiple lines
print("My name is Ankit.")
print("I am learning Python.")
print("I want to become a Python programmer.")

# Example 4: Print numbers
print(10)
print(100)
print(2026)

# Example 5: Basic arithmetic
print(5 + 3)   # Addition
print(10 - 4)  # Subtraction
print(6 * 7)   # Multiplication
print(10 / 2)  # Division

# Example 6: Use comments
# Python ignores comments when executing code
print("Comments help explain my code.")

# Example 7: Print text and numbers
print("I am", 20, "years old.")

# Example 8: Print a blank line
print("First line")
print()
print("Third line")

# Example 9: Use escape characters
print("Hello\nWorld")  # \n creates a new line
print("Python\tProgramming")  # \t adds a tab

# Example 10: Display a simple pattern
print("*")
print("**")
print("***")
print("****")

# End of my first Python lesson
print("I completed my first Python examples!")
